'use strict';
const test=require('node:test'),assert=require('node:assert/strict'),fs=require('node:fs');
const read=p=>JSON.parse(fs.readFileSync(p,'utf8'));
const source=read('sishu/chapters/daxue/01.json'),built=read('dist/sishu-content.json');
const alignment=read('dist/sishu-english-alignment.json');
const p=source.passages.find(p=>p.id==='sishu.daxue.01.01');
const bundled=built.chapters.flatMap(ch=>ch.passages).find(x=>x.id===p.id);
const text=x=>x.ruby_paragraphs.map(row=>row.map(t=>t.traditional||t.value||'').join('')).join('\n');
const fnv=s=>{let h=2166136261;for(let i=0;i<s.length;i++){h^=s.charCodeAt(i);h=Math.imul(h,16777619)>>>0;}return h.toString(16).padStart(8,'0')};
test('Da Xue main text 親民 unchanged and MATAKIN Indonesian preserved',()=>{
 assert.equal(p.editorial_status,'unverified-draft');
 assert.equal(text(p),'大學之道，在明明德，在親民，在止於至善。');
 assert.equal(fnv(text(p)),'1255a235');
 assert.equal(fnv(p.translation_indonesian),'e27ea699');
 const rubies=p.ruby_paragraphs.flat().filter(t=>t.type==='ruby');
 assert.equal(rubies.filter(t=>t.traditional==='親'&&t.pinyin==='qīn').length,1);
 assert.equal(rubies.filter(t=>t.traditional==='新').length,0);
 assert.deepEqual(p,bundled);
 assert.equal(built.chapters.length,78);
 assert.equal(built.chapters.reduce((n,ch)=>n+ch.passages.length,0),965);
 assert.equal(read('dist/sishu-review-status.json').entries.length,0);
});
test('Chengzi variant is in an attributed separate note with explicit edition caveat',()=>{
 assert.equal(p.editorial_annotations.length,1);
 const n=p.editorial_annotations[0];
 assert.equal(n.kind,'interpretive_comparison');
 assert.equal(n.after_paragraph_index,0);
 assert.equal(n.anchor_hanzi,'親民');
 assert.equal(n.reading_variants.project_main.hanzi,'親民');
 assert.equal(n.reading_variants.comparative.hanzi,'新民');
 assert.match(n.hanzi,/程子曰：「親，當作新。」/);
 assert.equal(n.source_witness.witness_file,'KR1h0015_000.txt');
 assert.equal(n.source_witness.witness_page,'KR1h0015_WYG_000-7a');
 assert.equal(n.source_witness.source_commit,'84c6b2c5093c57ae5d41c60a73c02323d2420ef0');
 assert.match(n.edition_caveat,/belum dikonfirmasi ulang/);
 assert.match(n.description_indonesian,/Legge/);
});
test('Legge translation remains verbatim and is marked as interpretively different',()=>{
 const matches=alignment.entries.filter(x=>x.indonesian_passage_ids.includes(p.id));
 assert.equal(matches.length,1);
 const e=matches[0];
 assert.equal(e.id,'legge-daxue-text-01');
 assert.equal(e.hanzi_span,text(p));
 assert.equal(e.status,'draft');
 assert.equal(e.source_url,'https://oll.libertyfund.org/title/2270');
 assert.equal(fnv(e.english_segments[0].text),'455a0be1');
 assert.match(e.english_segments[0].text,/to renovate the people/);
 assert.match(e.review_note,/tidak boleh disebut sepadan secara harfiah/);
 assert.match(e.review_note,/MATAKIN 2012/);
});
